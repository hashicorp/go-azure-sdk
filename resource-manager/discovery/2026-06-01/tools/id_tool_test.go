var _ resourceids.ResourceId = &ToolId{}

func TestNewToolID(t *testing.T) {
	id := NewToolID("12345678-1234-9876-4563-123456789012", "example-resource-group", "toolName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.ToolName != "toolName" {
		t.Fatalf("Expected %q but got %q for Segment 'ToolName'", id.ToolName, "toolName")
	}
}

func TestFormatToolID(t *testing.T) {
	actual := NewToolID("12345678-1234-9876-4563-123456789012", "example-resource-group", "toolName").ID()
	expected := "/subscriptions/12345678-1234-9876-4563-123456789012/resourceGroups/example-resource-group/providers/Microsoft.Discovery/tools/toolName"
	if actual != expected {
		t.Fatalf("Expected the Formatted ID to be %q but got %q", expected, actual)
	}
}

