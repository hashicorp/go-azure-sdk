var _ resourceids.ResourceId = &AigatewayId{}

func TestNewAigatewayID(t *testing.T) {
	id := NewAigatewayID("12345678-1234-9876-4563-123456789012", "example-resource-group", "aigatewayName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.AigatewayName != "aigatewayName" {
		t.Fatalf("Expected %q but got %q for Segment 'AigatewayName'", id.AigatewayName, "aigatewayName")
	}
}

func TestFormatAigatewayID(t *testing.T) {
	actual := NewAigatewayID("12345678-1234-9876-4563-123456789012", "example-resource-group", "aigatewayName").ID()
	expected := "/subscriptions/12345678-1234-9876-4563-123456789012/resourceGroups/example-resource-group/providers/Microsoft.Web/aigateways/aigatewayName"
	if actual != expected {
		t.Fatalf("Expected the Formatted ID to be %q but got %q", expected, actual)
	}
}

