var _ resourceids.ResourceId = &AssignedDeploymentId{}

func TestNewAssignedDeploymentID(t *testing.T) {
	id := NewAssignedDeploymentID("12345678-1234-9876-4563-123456789012", "example-resource-group", "goldenGateConnectionName", "assignmentId")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.GoldenGateConnectionName != "goldenGateConnectionName" {
		t.Fatalf("Expected %q but got %q for Segment 'GoldenGateConnectionName'", id.GoldenGateConnectionName, "goldenGateConnectionName")
	}

	if id.AssignmentId != "assignmentId" {
		t.Fatalf("Expected %q but got %q for Segment 'AssignmentId'", id.AssignmentId, "assignmentId")
	}
}

