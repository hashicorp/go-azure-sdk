func TestNewNodePoolID(t *testing.T) {
	id := NewNodePoolID("12345678-1234-9876-4563-123456789012", "example-resource-group", "hcpOpenShiftClusterName", "nodePoolName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.HcpOpenShiftClusterName != "hcpOpenShiftClusterName" {
		t.Fatalf("Expected %q but got %q for Segment 'HcpOpenShiftClusterName'", id.HcpOpenShiftClusterName, "hcpOpenShiftClusterName")
	}

	if id.NodePoolName != "nodePoolName" {
		t.Fatalf("Expected %q but got %q for Segment 'NodePoolName'", id.NodePoolName, "nodePoolName")
	}
}

