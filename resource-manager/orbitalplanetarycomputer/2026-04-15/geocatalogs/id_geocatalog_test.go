var _ resourceids.ResourceId = &GeoCatalogId{}

func TestNewGeoCatalogID(t *testing.T) {
	id := NewGeoCatalogID("12345678-1234-9876-4563-123456789012", "example-resource-group", "geoCatalogName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.GeoCatalogName != "geoCatalogName" {
		t.Fatalf("Expected %q but got %q for Segment 'GeoCatalogName'", id.GeoCatalogName, "geoCatalogName")
	}
}

func TestFormatGeoCatalogID(t *testing.T) {
	actual := NewGeoCatalogID("12345678-1234-9876-4563-123456789012", "example-resource-group", "geoCatalogName").ID()
	expected := "/subscriptions/12345678-1234-9876-4563-123456789012/resourceGroups/example-resource-group/providers/Microsoft.Orbital/geoCatalogs/geoCatalogName"
	if actual != expected {
		t.Fatalf("Expected the Formatted ID to be %q but got %q", expected, actual)
	}
}

