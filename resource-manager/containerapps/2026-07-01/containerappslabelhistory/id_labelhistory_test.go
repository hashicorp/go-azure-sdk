func TestNewLabelHistoryID(t *testing.T) {
	id := NewLabelHistoryID("12345678-1234-9876-4563-123456789012", "example-resource-group", "containerAppName", "labelHistoryName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.ContainerAppName != "containerAppName" {
		t.Fatalf("Expected %q but got %q for Segment 'ContainerAppName'", id.ContainerAppName, "containerAppName")
	}

	if id.LabelHistoryName != "labelHistoryName" {
		t.Fatalf("Expected %q but got %q for Segment 'LabelHistoryName'", id.LabelHistoryName, "labelHistoryName")
	}
}

