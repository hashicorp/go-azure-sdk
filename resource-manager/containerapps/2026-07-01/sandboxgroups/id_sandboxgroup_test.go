var _ resourceids.ResourceId = &SandboxGroupId{}

func TestNewSandboxGroupID(t *testing.T) {
	id := NewSandboxGroupID("12345678-1234-9876-4563-123456789012", "example-resource-group", "sandboxGroupName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.SandboxGroupName != "sandboxGroupName" {
		t.Fatalf("Expected %q but got %q for Segment 'SandboxGroupName'", id.SandboxGroupName, "sandboxGroupName")
	}
}

func TestFormatSandboxGroupID(t *testing.T) {
	actual := NewSandboxGroupID("12345678-1234-9876-4563-123456789012", "example-resource-group", "sandboxGroupName").ID()
	expected := "/subscriptions/12345678-1234-9876-4563-123456789012/resourceGroups/example-resource-group/providers/Microsoft.App/sandboxGroups/sandboxGroupName"
	if actual != expected {
		t.Fatalf("Expected the Formatted ID to be %q but got %q", expected, actual)
	}
}

