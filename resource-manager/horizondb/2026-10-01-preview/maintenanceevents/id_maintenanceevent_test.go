func TestNewMaintenanceEventID(t *testing.T) {
	id := NewMaintenanceEventID("12345678-1234-9876-4563-123456789012", "example-resource-group", "clusterName", "poolName", "maintenanceEventId")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.ClusterName != "clusterName" {
		t.Fatalf("Expected %q but got %q for Segment 'ClusterName'", id.ClusterName, "clusterName")
	}

	if id.PoolName != "poolName" {
		t.Fatalf("Expected %q but got %q for Segment 'PoolName'", id.PoolName, "poolName")
	}

	if id.MaintenanceEventId != "maintenanceEventId" {
		t.Fatalf("Expected %q but got %q for Segment 'MaintenanceEventId'", id.MaintenanceEventId, "maintenanceEventId")
	}
}

