var _ resourceids.ResourceId = &LinkId{}

func TestNewLinkID(t *testing.T) {
	id := NewLinkID("12345678-1234-9876-4563-123456789012", "example-resource-group", "expressRouteLagName", "linkName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.ExpressRouteLagName != "expressRouteLagName" {
		t.Fatalf("Expected %q but got %q for Segment 'ExpressRouteLagName'", id.ExpressRouteLagName, "expressRouteLagName")
	}

	if id.LinkName != "linkName" {
		t.Fatalf("Expected %q but got %q for Segment 'LinkName'", id.LinkName, "linkName")
	}
}

func TestFormatLinkID(t *testing.T) {
	actual := NewLinkID("12345678-1234-9876-4563-123456789012", "example-resource-group", "expressRouteLagName", "linkName").ID()
	expected := "/subscriptions/12345678-1234-9876-4563-123456789012/resourceGroups/example-resource-group/providers/Microsoft.Network/expressRouteLags/expressRouteLagName/links/linkName"
	if actual != expected {
		t.Fatalf("Expected the Formatted ID to be %q but got %q", expected, actual)
	}
}

