func TestNewConnectionAnalyzerID(t *testing.T) {
	id := NewConnectionAnalyzerID("12345678-1234-9876-4563-123456789012", "example-resource-group", "networkWatcherName", "connectionAnalyzerName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.NetworkWatcherName != "networkWatcherName" {
		t.Fatalf("Expected %q but got %q for Segment 'NetworkWatcherName'", id.NetworkWatcherName, "networkWatcherName")
	}

	if id.ConnectionAnalyzerName != "connectionAnalyzerName" {
		t.Fatalf("Expected %q but got %q for Segment 'ConnectionAnalyzerName'", id.ConnectionAnalyzerName, "connectionAnalyzerName")
	}
}

