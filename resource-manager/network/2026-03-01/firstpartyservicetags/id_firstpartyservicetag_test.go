func TestNewFirstPartyServiceTagID(t *testing.T) {
	id := NewFirstPartyServiceTagID("12345678-1234-9876-4563-123456789012", "example-resource-group", "firstPartyServiceTagName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.FirstPartyServiceTagName != "firstPartyServiceTagName" {
		t.Fatalf("Expected %q but got %q for Segment 'FirstPartyServiceTagName'", id.FirstPartyServiceTagName, "firstPartyServiceTagName")
	}
}

