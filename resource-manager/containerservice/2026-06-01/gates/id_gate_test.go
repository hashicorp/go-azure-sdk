var _ resourceids.ResourceId = &GateId{}

func TestNewGateID(t *testing.T) {
	id := NewGateID("12345678-1234-9876-4563-123456789012", "example-resource-group", "fleetName", "gateName")

	if id.SubscriptionId != "12345678-1234-9876-4563-123456789012" {
		t.Fatalf("Expected %q but got %q for Segment 'SubscriptionId'", id.SubscriptionId, "12345678-1234-9876-4563-123456789012")
	}

	if id.ResourceGroupName != "example-resource-group" {
		t.Fatalf("Expected %q but got %q for Segment 'ResourceGroupName'", id.ResourceGroupName, "example-resource-group")
	}

	if id.FleetName != "fleetName" {
		t.Fatalf("Expected %q but got %q for Segment 'FleetName'", id.FleetName, "fleetName")
	}

	if id.GateName != "gateName" {
		t.Fatalf("Expected %q but got %q for Segment 'GateName'", id.GateName, "gateName")
	}
}

func TestFormatGateID(t *testing.T) {
	actual := NewGateID("12345678-1234-9876-4563-123456789012", "example-resource-group", "fleetName", "gateName").ID()
	expected := "/subscriptions/12345678-1234-9876-4563-123456789012/resourceGroups/example-resource-group/providers/Microsoft.ContainerService/fleets/fleetName/gates/gateName"
	if actual != expected {
		t.Fatalf("Expected the Formatted ID to be %q but got %q", expected, actual)
	}
}

